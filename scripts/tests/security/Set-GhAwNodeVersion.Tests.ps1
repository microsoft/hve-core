BeforeAll {
    . (Join-Path $PSScriptRoot '../../security/Set-GhAwNodeVersion.ps1')

    function script:New-GhAwFixture {
        param(
            [string]$DetectionVersionInput = "          node-version: '24'",
            [string]$NodeVersion = '24.21.0'
        )

        $Root = Join-Path $TestDrive ([guid]::NewGuid().ToString())
        $WorkflowRoot = Join-Path $Root '.github/workflows'
        $SecurityRoot = Join-Path $Root 'scripts/security'
        New-Item -ItemType Directory -Path $WorkflowRoot, $SecurityRoot -Force | Out-Null

        @{ tools = @(@{ name = 'gh-aw'; version = '0.89.21' }) } |
            ConvertTo-Json -Depth 5 |
            Set-Content -LiteralPath (Join-Path $SecurityRoot 'tool-checksums.json') -Encoding utf8
        Set-Content -LiteralPath (Join-Path $Root '.node-version') -Value $NodeVersion -Encoding utf8
        Set-Content -LiteralPath (Join-Path $WorkflowRoot 'fixture.md') -Value "---`nname: fixture`n---" -Encoding utf8

        @"
# gh-aw-metadata: {"compiler_version":"v0.89.21"}
jobs:
  agent:
    steps:
      - name: Setup Node.js
        uses: actions/setup-node@$('b' * 40) # v7.0.0
        with:
          node-version: '24.21.0'
  detection:
    steps:
      - name: Setup Node.js
        uses: actions/setup-node@$('b' * 40) # v7.0.0
        with:
$DetectionVersionInput
          package-manager-cache: false
  conclusion:
    steps: []
"@ | Set-Content -LiteralPath (Join-Path $WorkflowRoot 'fixture.lock.yml') -Encoding utf8

        return $Root
    }
}

Describe 'Set-GhAwNodeVersion' -Tag 'Unit' {
    It 'normalizes only the declared detection setup-node input' {
        $Root = New-GhAwFixture

        $Result = Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture'
        $Lock = Get-Content -LiteralPath (Join-Path $Root '.github/workflows/fixture.lock.yml') -Raw

        $Result.Count | Should -Be 1
        $Result[0].Changed | Should -BeTrue
        $Result[0].NodeVersion | Should -BeExactly '24.21.0'
        ([regex]::Matches($Lock, "node-version: '24\.21\.0'")).Count | Should -Be 2
        $Lock | Should -Not -Match "node-version: '24'"
        $Lock | Should -Not -Match 'actions/checkout'
    }

    It 'uses the exact current repository Node version' {
        $Root = New-GhAwFixture -NodeVersion '25.3.1'

        Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' | Out-Null

        Get-Content -LiteralPath (Join-Path $Root '.github/workflows/fixture.lock.yml') -Raw |
            Should -Match "node-version: '25\.3\.1'"
    }

    It 'verifies an already-normalized generated lock without rewriting it' {
        $Root = New-GhAwFixture -DetectionVersionInput "          node-version: '24.21.0'"
        $LockPath = Join-Path $Root '.github/workflows/fixture.lock.yml'
        $Before = [System.IO.File]::ReadAllBytes($LockPath)

        $Result = Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' -VerifyOnly

        $Result[0].Changed | Should -BeFalse
        [System.IO.File]::ReadAllBytes($LockPath) | Should -Be $Before
    }

    It 'rejects verification while the generated floating input remains' {
        $Root = New-GhAwFixture

        { Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' -VerifyOnly } |
            Should -Throw '*floating detection Node version*'
    }

    It 'rejects an invalid repository Node version' {
        $Root = New-GhAwFixture -NodeVersion '24'

        { Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' } |
            Should -Throw '*.node-version must contain exactly one X.Y.Z*'
    }

    It 'rejects a setup-node step without its generated version comment' {
        $Root = New-GhAwFixture
        $LockPath = Join-Path $Root '.github/workflows/fixture.lock.yml'
        (Get-Content -LiteralPath $LockPath -Raw).Replace(
            "actions/setup-node@$([string]('b' * 40)) # v7.0.0",
            "actions/setup-node@$([string]('b' * 40))"
        ) | Set-Content -LiteralPath $LockPath -Encoding utf8

        { Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' } |
            Should -Throw '*version-commented setup-node step*'
    }

    It 'rejects locks generated by a different compiler version' {
        $Root = New-GhAwFixture
        $LockPath = Join-Path $Root '.github/workflows/fixture.lock.yml'
        (Get-Content -LiteralPath $LockPath -Raw).Replace(
            '"compiler_version":"v0.89.21"',
            '"compiler_version":"v0.90.0"'
        ) | Set-Content -LiteralPath $LockPath -Encoding utf8

        { Set-GhAwNodeVersion -Root $Root -WorkflowIds 'fixture' } |
            Should -Throw '*compiler version does not match*'
    }
}
