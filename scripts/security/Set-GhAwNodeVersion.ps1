<#
.SYNOPSIS
    Normalizes generated gh-aw detection jobs to the repository Node version.

.DESCRIPTION
    Reads the exact runtime from the repository .node-version file, validates
    each declared lock was generated by the repository-pinned gh-aw version,
    and replaces only gh-aw's hard-coded detection-job `node-version: '24'`
    input with that exact runtime.

    The operation fails closed on missing, duplicate, or structurally changed
    generated steps. Use Verify to check already-normalized locks without writing.

.PARAMETER RepoRoot
    Repository root. Defaults to the current Git repository root.

.PARAMETER Verify
    Validates that every declared lock is already normalized without modifying it.

.EXAMPLE
    ./scripts/security/Set-GhAwNodeVersion.ps1

.EXAMPLE
    ./scripts/security/Set-GhAwNodeVersion.ps1 -Verify

.NOTES
    Run this script immediately after `gh aw compile` with the gh-aw version
    pinned in scripts/security/tool-checksums.json.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [string]$RepoRoot,

    [Parameter(Mandatory = $false)]
    [switch]$Verify
)

$ErrorActionPreference = 'Stop'

$script:GhAwNodeWorkflows = @(
    'demo-material-author'
    'dependency-pr-review'
    'doc-update-check'
    'issue-implement'
    'issue-triage'
    'pr-review'
    'vex-draft'
)

#region Functions

function Get-RepositoryRoot {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $false)]
        [string]$Path
    )

    if (-not [string]::IsNullOrWhiteSpace($Path)) {
        return [System.IO.Path]::GetFullPath($Path)
    }

    $GitRoot = git rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($GitRoot)) {
        throw 'Unable to resolve the repository root.'
    }

    return [System.IO.Path]::GetFullPath($GitRoot.Trim())
}

function Get-PinnedGhAwVersion {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Root
    )

    $ManifestPath = Join-Path $Root 'scripts/security/tool-checksums.json'
    if (-not (Test-Path -LiteralPath $ManifestPath -PathType Leaf)) {
        throw "Tool manifest not found: $ManifestPath"
    }

    $Manifest = Get-Content -LiteralPath $ManifestPath -Raw | ConvertFrom-Json
    $GhAwTools = @($Manifest.tools | Where-Object name -EQ 'gh-aw')
    if ($GhAwTools.Count -ne 1 -or [string]::IsNullOrWhiteSpace($GhAwTools[0].version)) {
        throw 'Tool manifest must contain exactly one versioned gh-aw entry.'
    }

    return [string]$GhAwTools[0].version
}

function Get-RepositoryNodeVersion {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Root
    )

    $VersionPath = Join-Path $Root '.node-version'
    if (-not (Test-Path -LiteralPath $VersionPath -PathType Leaf)) {
        throw "Node version file not found: $VersionPath"
    }

    $Version = (Get-Content -LiteralPath $VersionPath -Raw).Trim()
    if ($Version -notmatch '^\d+\.\d+\.\d+$') {
        throw '.node-version must contain exactly one X.Y.Z runtime version.'
    }

    return $Version
}

function Set-GhAwNodeVersion {
    [CmdletBinding()]
    [OutputType([pscustomobject[]])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Root,

        [Parameter(Mandatory = $false)]
        [string[]]$WorkflowIds = $script:GhAwNodeWorkflows,

        [Parameter(Mandatory = $false)]
        [switch]$VerifyOnly
    )

    $ResolvedRoot = Get-RepositoryRoot -Path $Root
    $WorkflowRoot = Join-Path $ResolvedRoot '.github/workflows'
    $PinnedVersion = Get-PinnedGhAwVersion -Root $ResolvedRoot
    $NodeVersion = Get-RepositoryNodeVersion -Root $ResolvedRoot
    if ($WorkflowIds.Count -eq 0 -or @($WorkflowIds | Select-Object -Unique).Count -ne $WorkflowIds.Count) {
        throw 'WorkflowIds must contain one or more unique workflow identifiers.'
    }

    $Results = foreach ($WorkflowId in $WorkflowIds) {
        if ($WorkflowId -notmatch '^[a-z0-9][a-z0-9-]*$') {
            throw "Invalid workflow identifier: $WorkflowId"
        }

        $SourcePath = Join-Path $WorkflowRoot "$WorkflowId.md"
        $LockPath = Join-Path $WorkflowRoot "$WorkflowId.lock.yml"
        if (-not (Test-Path -LiteralPath $SourcePath -PathType Leaf)) {
            throw "Canonical workflow source not found: $SourcePath"
        }
        if (-not (Test-Path -LiteralPath $LockPath -PathType Leaf)) {
            throw "Generated workflow lock not found: $LockPath"
        }

        $LockText = Get-Content -LiteralPath $LockPath -Raw
        $CompilerMatches = [regex]::Matches($LockText, '(?m)^# gh-aw-metadata: .*"compiler_version":"v([^"]+)"')
        if ($CompilerMatches.Count -ne 1 -or $CompilerMatches[0].Groups[1].Value -ne $PinnedVersion) {
            throw "Generated lock compiler version does not match pinned gh-aw $PinnedVersion`: $LockPath"
        }

        $DetectionMatches = [regex]::Matches(
            $LockText,
            '(?ms)^  detection:\r?\n.*?(?=^  [A-Za-z0-9_-]+:\s*(?:#.*)?\r?$|\z)'
        )
        if ($DetectionMatches.Count -ne 1) {
            throw "Generated lock must contain exactly one detection job: $LockPath"
        }

        $Detection = $DetectionMatches[0].Value
        $SetupMatches = [regex]::Matches(
            $Detection,
            '(?m)^      - name: Setup Node\.js\r?\n' +
            '        uses: actions/setup-node@[0-9a-f]{40} # v\d+\.\d+\.\d+\r?\n' +
            '        with:\r?$'
        )
        if ($SetupMatches.Count -ne 1) {
            throw "Detection job must contain exactly one version-commented setup-node step: $LockPath"
        }

        $GeneratedPattern = "(?m)^          node-version:\s*'24'\s*\r?$"
        $NormalizedPattern = "(?m)^          node-version:\s*'$([regex]::Escape($NodeVersion))'\s*\r?$"
        $GeneratedMatches = [regex]::Matches($Detection, $GeneratedPattern)
        $NormalizedMatches = [regex]::Matches($Detection, $NormalizedPattern)
        if (($GeneratedMatches.Count + $NormalizedMatches.Count) -ne 1) {
            throw "Detection setup-node must contain exactly one supported Node version input: $LockPath"
        }

        if ($VerifyOnly -and $GeneratedMatches.Count -ne 0) {
            throw "Generated lock still uses gh-aw's floating detection Node version: $LockPath"
        }

        $Changed = $false
        if (-not $VerifyOnly -and $GeneratedMatches.Count -eq 1) {
            $NormalizedDetection = [regex]::Replace(
                $Detection,
                $GeneratedPattern,
                "          node-version: '$NodeVersion'",
                1
            )
            $LockText = $LockText.Substring(0, $DetectionMatches[0].Index) +
                $NormalizedDetection +
                $LockText.Substring($DetectionMatches[0].Index + $DetectionMatches[0].Length)
            [System.IO.File]::WriteAllText(
                $LockPath,
                $LockText,
                [System.Text.UTF8Encoding]::new($false)
            )
            $Changed = $true
        }

        [pscustomobject]@{
            Source = [System.IO.Path]::GetRelativePath($ResolvedRoot, $SourcePath)
            Lock = [System.IO.Path]::GetRelativePath($ResolvedRoot, $LockPath)
            NodeVersion = $NodeVersion
            Changed = $Changed
        }
    }

    return @($Results)
}

#endregion Functions

#region Main Execution

if ($MyInvocation.InvocationName -ne '.') {
    try {
        $ResolvedRoot = Get-RepositoryRoot -Path $RepoRoot
        $Results = Set-GhAwNodeVersion -Root $ResolvedRoot -VerifyOnly:$Verify
        $ChangedCount = @($Results | Where-Object Changed).Count
        $Mode = if ($Verify) { 'verified' } else { 'normalized' }
        Write-Host "gh-aw Node versions $Mode`: $($Results.Count) checked, $ChangedCount changed" -ForegroundColor Green
    }
    catch {
        Write-Error -ErrorAction Continue "Set-GhAwNodeVersion failed: $($_.Exception.Message)"
        exit 1
    }
}

#endregion Main Execution
